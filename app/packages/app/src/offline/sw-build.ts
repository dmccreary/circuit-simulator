// Build-time half of offline operation (PRF-07, files-and-persistence.md §6):
// the precache list and the service worker's source, emitted next to the
// built app as `sw.js` by the Vite plugin below. The worker is scoped to the
// simulator's own folder, so it never touches the rest of the book.
//
// Caches:
//   cs-shell-<version>  the app shell: index.html and every built asset
//                       (precached on install; the two newest versions are
//                       kept so a tab still on the old version can load its
//                       lazy chunks after another tab updated)
//   cs-content-v1       example circuits (cache first; the whole library is
//                       fetched in the background after activation) and
//                       lessons or other circuit files (network first,
//                       cached for offline use)

/** Files from the build output that make up the app shell. */
export function precacheList(files: readonly string[]): string[] {
  const keep = (f: string) =>
    !f.endsWith(".map") &&
    f !== "sw.js" &&
    !f.startsWith("circuits/") &&
    !f.startsWith("lessons/") &&
    /\.(html|js|mjs|css|svg|png|ico|webp|woff2?|json|webmanifest)$/.test(f);
  const list = [...new Set(files.filter(keep))].sort();
  return ["./", ...list.map((f) => `./${f}`), "./circuits/index.json"].filter((f, i, a) => a.indexOf(f) === i);
}

/** Short stable hash (FNV-1a) of the inputs, used as the shell cache version. */
export function versionOf(parts: readonly string[]): string {
  let h = 0x811c9dc5;
  for (const p of parts)
    for (let i = 0; i < p.length; i++) {
      h ^= p.charCodeAt(i);
      h = Math.imul(h, 0x01000193) >>> 0;
    }
  return h.toString(36);
}

export const CONTENT_CACHE = "cs-content-v1";

/** The service worker, as plain JavaScript. */
export function serviceWorkerSource(version: string, precache: readonly string[]): string {
  return `// Circuit Simulator service worker (generated by packages/app/src/offline/sw-build.ts).
"use strict";
const VERSION = ${JSON.stringify(version)};
const SHELL = "cs-shell-" + VERSION;
const CONTENT = ${JSON.stringify(CONTENT_CACHE)};
const PRECACHE = ${JSON.stringify(precache)};
const SCOPE = self.registration.scope;

self.addEventListener("install", (event) => {
  // Never skipWaiting here: a running session must not change version under it.
  event.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE.map((u) => new URL(u, SCOPE).href))));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const shells = (await caches.keys()).filter((k) => k.startsWith("cs-shell-") && k !== SHELL);
      // Keep the newest previous version for tabs still running it.
      for (const old of shells.slice(0, -1)) await caches.delete(old);
      await self.clients.claim();
      warmExamples();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "skip-waiting") self.skipWaiting();
  if (event.data && event.data.type === "warm-examples") warmExamples();
});

/** Fetch the whole example library in the background so it works offline (FIL-13). */
async function warmExamples() {
  try {
    const index = await (await fetch(new URL("circuits/index.json", SCOPE))).json();
    const cache = await caches.open(CONTENT);
    for (const e of index.circuits || []) {
      const url = new URL("circuits/" + encodeURIComponent(e.file), SCOPE).href;
      if (await cache.match(url)) continue;
      const res = await fetch(url).catch(() => undefined);
      if (res && res.ok) await cache.put(url, res);
    }
  } catch (e) {
    // offline or no library in this build: examples are cached when opened
  }
}

const isContent = (url) => /\\.(txt|ya?ml|json|md|cir|circuit)$/i.test(url.pathname);

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  const inScope = req.url.startsWith(SCOPE);

  if (req.mode === "navigate") {
    if (!inScope) return;
    // The shell for any address in the simulator folder (?lesson=, #c=, ...).
    event.respondWith(
      caches.match(new URL("./", SCOPE).href).then((hit) => hit || fetch(req)).catch(() => fetch(req)),
    );
    return;
  }
  if (inScope && url.pathname.startsWith(new URL("circuits/", SCOPE).pathname)) {
    event.respondWith(cacheFirst(req));
    return;
  }
  if (inScope && !isContent(url)) {
    event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
    return;
  }
  if (isContent(url)) event.respondWith(networkFirst(req));
});

async function cacheFirst(req) {
  const hit = await caches.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok) (await caches.open(CONTENT)).put(req, res.clone());
  return res;
}

async function networkFirst(req) {
  try {
    const res = await fetch(req);
    if (res.ok) (await caches.open(CONTENT)).put(req, res.clone());
    return res;
  } catch (e) {
    const hit = await caches.match(req);
    if (hit) return hit;
    throw e;
  }
}
`;
}

/** Minimal shape of the Vite/Rollup plugin API used here (no dependency on Vite's types). */
interface BundleFile {
  type: "chunk" | "asset";
  fileName: string;
  code?: string;
  source?: string | Uint8Array;
}
interface PluginContext {
  emitFile(f: { type: "asset"; fileName: string; source: string }): void;
}

/**
 * Vite plugin: after the bundle is written out, emit `sw.js` precaching every
 * shell file. `extra` names public files to add to the version hash (the
 * example index), read by the caller.
 */
export function offlinePlugin(opts: { extraVersionInputs?: () => string[] } = {}) {
  return {
    name: "circuit-simulator-offline",
    apply: "build" as const,
    enforce: "post" as const,
    generateBundle(this: PluginContext, _out: unknown, bundle: Record<string, BundleFile>) {
      const files = Object.keys(bundle);
      const precache = precacheList(files);
      const inputs = files.sort().map((f) => {
        const b = bundle[f];
        const body = b.type === "chunk" ? (b.code ?? "") : typeof b.source === "string" ? b.source : String(b.source?.length ?? 0);
        return `${f}:${body.length}:${versionOf([body])}`;
      });
      const version = versionOf([...inputs, ...(opts.extraVersionInputs?.() ?? [])]);
      this.emitFile({ type: "asset", fileName: "sw.js", source: serviceWorkerSource(version, precache) });
    },
  };
}
